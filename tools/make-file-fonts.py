"""Regenerate css/fonts-file.css.

Browsers block web fonts on pages opened straight from a folder (file://),
because font requests always use CORS and a file page has no origin.
css/fonts-file.css embeds the same fonts as data URIs and is only loaded
when the site runs from file://. Run this after changing a font file:

    python tools/make-file-fonts.py
"""
import base64, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
fonts = root / "assets" / "fonts"

FACES = [
    ("Archivo", "archivo.woff2", "normal", "100 900", "font-stretch: 62% 125%;"),
    ("Source Serif 4", "source-serif-italic.woff2", "italic", "200 900", ""),
]

out = ["/* Generated by tools/make-file-fonts.py. Do not edit by hand.",
       "   Loaded only when index.html is opened from a folder (file://). */"]
for family, file, style, weight, extra in FACES:
    data = base64.b64encode((fonts / file).read_bytes()).decode("ascii")
    out.append(
        '@font-face { font-family: "%s"; src: url(data:font/woff2;base64,%s) format("woff2"); '
        "font-weight: %s; font-style: %s; %s font-display: swap; }" % (family, data, weight, style, extra)
    )
(root / "css" / "fonts-file.css").write_text("\n".join(out) + "\n", encoding="ascii")
print("wrote css/fonts-file.css")
